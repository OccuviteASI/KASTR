#!/usr/bin/env bash
# Builds the KASTR probe APK (a test app, not the real KASTR app) with plain JDK + Android build-tools, no Gradle.
#   wsl -u root -e bash android/probe/build.sh          (from the repo root)
# Output: dist/android/kastr-probe-<version>.apk
# Needs (see android/README.md): openjdk-17-jdk-headless, build-tools r34 (aapt2, d8, zipalign, apksigner) and
# android-34 android.jar. Signs with a local TEST keystore kept outside the repo; it is made on the first build.
set -euo pipefail

PROBE_VERSION="0.21.92"
VERSION_CODE="2192"

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
SDK="${ANDROID_SDK:-/opt/android-sdk}"
BT="${BUILD_TOOLS:-$SDK/build-tools-34/android-14}"
JAR="${ANDROID_JAR:-$SDK/platform-34/android-34/android.jar}"
KS="${PROBE_KEYSTORE:-/mnt/c/kastr-scratch/android/probe-test.keystore}"
PASSFILE="${KS%.keystore}.pass"
OUTDIR="$REPO/dist/android"
OUT="${PROBE_OUT:-$OUTDIR/kastr-probe-$PROBE_VERSION.apk}"   # PROBE_OUT: tests build elsewhere

for tool in "$BT/aapt2" "$BT/d8" "$BT/zipalign" "$BT/apksigner" "$BT/core-lambda-stubs.jar" "$JAR"; do
  [ -e "$tool" ] || { echo "missing: $tool (see android/README.md)" >&2; exit 2; }
done
for cmd in javac java keytool python3; do
  command -v "$cmd" >/dev/null || { echo "missing command: $cmd" >&2; exit 2; }
done

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
mkdir -p "$WORK/gen/app/kastr/probe" "$WORK/classes" "$WORK/dex" "$WORK/qrtest"

echo "== 1/7 QR encoder self-test (desktop JVM)"
javac -encoding UTF-8 -d "$WORK/qrtest" "$HERE/src/app/kastr/probe/QrCode.java" "$HERE/test/QrCodeTest.java"
java -cp "$WORK/qrtest" app.kastr.probe.QrCodeTest

echo "== 2/7 resources (aapt2)"
"$BT/aapt2" compile --dir "$HERE/res" -o "$WORK/res.zip"
"$BT/aapt2" link -I "$JAR" --manifest "$HERE/AndroidManifest.xml" -A "$HERE/assets" \
  --version-code "$VERSION_CODE" --version-name "$PROBE_VERSION" \
  --java "$WORK/gen" -o "$WORK/base.apk" "$WORK/res.zip"

cat > "$WORK/gen/app/kastr/probe/BuildInfo.java" <<EOF
package app.kastr.probe;

/** Generated by android/probe/build.sh. */
final class BuildInfo {
    static final String VERSION = "$PROBE_VERSION";
    private BuildInfo() {}
}
EOF

echo "== 3/7 compile (javac, Java 8 bytecode against android-34)"
find "$HERE/src" "$WORK/gen" -name '*.java' > "$WORK/sources.txt"
javac -encoding UTF-8 -source 8 -target 8 -Xlint:-options -bootclasspath "$JAR:$BT/core-lambda-stubs.jar" -classpath "$JAR" \
  -d "$WORK/classes" @"$WORK/sources.txt"

echo "== 4/7 dex (d8, min API 24)"
find "$WORK/classes" -name '*.class' > "$WORK/classes.txt"
"$BT/d8" --release --min-api 24 --lib "$JAR" --output "$WORK/dex" @"$WORK/classes.txt"

echo "== 5/7 package + align"
cp "$WORK/base.apk" "$WORK/unaligned.apk"
python3 -I - "$WORK/unaligned.apk" "$WORK/dex/classes.dex" <<'PY'
import sys, zipfile
apk, dex = sys.argv[1], sys.argv[2]
with zipfile.ZipFile(apk, "a", compression=zipfile.ZIP_DEFLATED) as z:
    z.write(dex, "classes.dex")
PY
"$BT/zipalign" -p -f 4 "$WORK/unaligned.apk" "$WORK/aligned.apk"

echo "== 6/7 sign (test keystore, v1 + v2)"
if [ ! -f "$KS" ]; then
  mkdir -p "$(dirname "$KS")"
  ( umask 077; head -c 32 /dev/urandom | base64 | tr -d '/+=\n' | head -c 32 > "$PASSFILE" )
  chmod 600 "$PASSFILE" || true
  keytool -genkeypair -noprompt -keystore "$KS" -storetype PKCS12 -alias probe -keyalg RSA -keysize 2048 \
    -validity 10000 -dname "CN=KASTR probe TEST key, O=KASTR test" \
    -storepass:file "$PASSFILE" -keypass:file "$PASSFILE" >/dev/null
  echo "made a new test keystore at $KS (password in $(basename "$PASSFILE"), not printed)"
fi
[ -f "$PASSFILE" ] || { echo "missing keystore password file $PASSFILE" >&2; exit 2; }
mkdir -p "$(dirname "$OUT")"
"$BT/apksigner" sign --ks "$KS" --ks-key-alias probe --ks-pass "file:$PASSFILE" \
  --v1-signing-enabled true --v2-signing-enabled true --v3-signing-enabled false --v4-signing-enabled false \
  --out "$OUT" "$WORK/aligned.apk"
rm -f "$OUT.idsig"

echo "== 7/7 verify"
"$BT/zipalign" -c -p 4 "$OUT" && echo "zipalign: ok"
"$BT/apksigner" verify --min-sdk-version 18 --verbose --print-certs "$OUT" | grep -E '^(Verifies|Verified using|Signer #1 certificate (DN|SHA-256))'
"$BT/aapt2" dump badging "$OUT" | grep -E "^ *(package|sdkVersion|targetSdkVersion|uses-permission|application:|launchable-activity|leanback-launchable-activity|uses-feature|uses-implied)" || true
echo "APK: $OUT"
echo "size: $(stat -c %s "$OUT") bytes"
echo "sha256: $(sha256sum "$OUT" | cut -d' ' -f1)"
